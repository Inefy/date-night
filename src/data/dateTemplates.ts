import type { DateStep, DateTemplate } from '@/types/domain';

const deckTimestamp = '2026-05-30T00:00:00.000Z';

type StepSeed = {
  title: string;
  description: string;
  durationMinutes?: number;
};

type DateTemplateSeed = Omit<DateTemplate, 'createdAt' | 'updatedAt' | 'steps'> & {
  steps: StepSeed[];
};

function makeSteps(templateId: string, steps: StepSeed[]): DateStep[] {
  return steps.map(({ title, description, durationMinutes }, index) => {
    const step: DateStep = {
      id: `${templateId}-step-${index + 1}`,
      title,
      description,
      sortOrder: index + 1,
    };

    if (durationMinutes !== undefined) {
      step.durationMinutes = durationMinutes;
    }

    return step;
  });
}

function makeTemplate(template: DateTemplateSeed): DateTemplate {
  return {
    ...template,
    steps: makeSteps(template.id, template.steps),
    createdAt: deckTimestamp,
    updatedAt: deckTimestamp,
  };
}

